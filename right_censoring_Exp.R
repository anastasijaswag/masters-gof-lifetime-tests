# ==============================================================================
# right_censoring_Exp.R
# Критерии Крамера–фон Мизеса и Андерсона–Дарлинга для правоцензурированных
# данных II типа: проверка экспоненциального распределения
# D'Agostino & Stephens (1986), таблицы критических значений
# ==============================================================================

# ------------------------------------------------------------------------------
# Основная функция: критерии W² и A² для правоцензурированной выборки II типа
#
#   H0: данные из экспоненциального распределения Exp(eta)
#
# Аргументы:
#   x_obs  — наблюдаемые значения (отсортированные первые m из n, m = length(x_obs))
#   n      — полный объём выборки (включая цензурированные наблюдения)
#   alpha  — уровень значимости (по умолчанию 0.05)
# ------------------------------------------------------------------------------

CENS.test.my <- function(x_obs, n, alpha = 0.05) {

  m <- length(x_obs)
  x <- sort(x_obs)

  # МПО параметра масштаба экспоненты по данным II типа цензуры
  eta <- (sum(x) + (n - m) * x[m]) / m

  # PIT: z_i = F(x_i; eta_hat) = 1 - exp(-x_i / eta)
  z <- 1 - exp(-x / eta)

  # Статистика W² (Stephens, ур. 4.2.2 с поправкой на цензуру)
  i_vec <- seq_len(m)
  W2 <- sum((z - (2 * i_vec - 1) / (2 * n))^2) +
    m / (12 * n^2) +
    (n / 3) * (z[m] - m / n)^3

  # Статистика A² (Stephens, ур. 4.2.4)
  A2 <- -(1 / n) * sum((2 * i_vec - 1) * (log(z) - log(1 - z))) -
    2 * sum(log(1 - z)) -
    (1 / n) * ((m - n)^2 * log(1 - z[m]) - m^2 * log(z[m]) + n^2 * z[m])

  # ------------------------------------------------------------------------------
  # Таблицы критических значений (alpha = 0.05)
  # Строки: доля цензурирования = 0, 10%, ..., 80%  (9 строк)
  # Столбцы: n = 10, 20, ..., 100, Inf              (11 столбцов)
  # Источник: D'Agostino & Stephens (1986)
  # ------------------------------------------------------------------------------

  W2_tab <- matrix(c(
    0.2160, 0.1820, 0.1560, 0.1300, 0.1040, 0.0795, 0.0550, 0,      0,
    0.2210, 0.1940, 0.1670, 0.1365, 0.1060, 0.0810, 0.0560, 0.0370, 0.0180,
    0.2195, 0.1935, 0.1670, 0.1377, 0.1070, 0.0820, 0.0560, 0.0368, 0.0175,
    0.2180, 0.1930, 0.1670, 0.1380, 0.1090, 0.0825, 0.0560, 0.0365, 0.0170,
    0.2185, 0.1940, 0.1675, 0.1383, 0.1090, 0.0825, 0.0560, 0.0365, 0.0170,
    0.2190, 0.1950, 0.1680, 0.1385, 0.1090, 0.0825, 0.0560, 0.0365, 0.0170,
    0.2195, 0.1955, 0.1685, 0.1388, 0.1090, 0.0825, 0.0560, 0.0365, 0.0170,
    0.2200, 0.1960, 0.1690, 0.1390, 0.1090, 0.0825, 0.0560, 0.0365, 0.0170,
    0.2200, 0.1960, 0.1690, 0.1390, 0.1090, 0.0825, 0.0560, 0.0365, 0.0170,
    0.2200, 0.1960, 0.1690, 0.1390, 0.1090, 0.0825, 0.0560, 0.0365, 0.0170,
    0.2220, 0.1990, 0.1700, 0.1400, 0.1100, 0.0830, 0.0560, 0.0360, 0.0160
  ), nrow = 9, ncol = 11)

  A2_tab <- matrix(c(
    1.2780, 1.0590, 0.9290, 0.8065, 0.6840, 0.5645, 0.4450, 0,      0,
    1.3150, 1.1170, 0.9790, 0.8500, 0.7210, 0.5990, 0.4770, 0.3545, 0.2320,
    1.3070, 1.1170, 0.9820, 0.8550, 0.7270, 0.6040, 0.4810, 0.3590, 0.2365,
    1.2990, 1.1170, 0.9850, 0.8590, 0.7330, 0.6090, 0.4850, 0.3630, 0.2410,
    1.3010, 1.1220, 0.9870, 0.8593, 0.7320, 0.6103, 0.4890, 0.3658, 0.2425,
    1.3030, 1.1270, 0.9890, 0.8595, 0.7300, 0.6115, 0.4930, 0.3685, 0.2440,
    1.3045, 1.1295, 0.9900, 0.8600, 0.7305, 0.6125, 0.4945, 0.3710, 0.2465,
    1.3060, 1.1320, 0.9910, 0.8610, 0.7310, 0.6135, 0.4960, 0.3725, 0.2490,
    1.3070, 1.1335, 0.9920, 0.8620, 0.7320, 0.6143, 0.4965, 0.3735, 0.2505,
    1.3080, 1.1350, 0.9930, 0.8630, 0.7330, 0.6150, 0.4970, 0.3745, 0.2520,
    1.3210, 1.1490, 1.0030, 0.8745, 0.7460, 0.6235, 0.5010, 0.3875, 0.2740
  ), nrow = 9, ncol = 11)

  # Индексы в таблице
  cens_pct <- (n - m) / n
  row_idx  <- round(cens_pct * 10, 0) + 1       # 1..9 (доля цензурирования 0%..80%)
  col_idx  <- min(ifelse(n > 100, 11, n / 10), 11)

  if (row_idx < 1 || row_idx > 9)  return(NULL)
  if (col_idx < 1 || col_idx > 11) return(NULL)

  W2_crit <- W2_tab[row_idx, col_idx]
  A2_crit <- A2_tab[row_idx, col_idx]

  if (W2_crit == 0 || A2_crit == 0) return(NULL)

  W2_reject <- W2 > W2_crit
  A2_reject <- A2 > A2_crit

  result <- list(
    test           = "Крамера–фон Мизеса и Андерсона–Дарлинга",
    distribution   = "экспоненциальное",
    data_type      = "правоцензурированная выборка II типа",
    hypothesis     = "H0: выборка согласуется с экспоненциальным распределением",
    alpha          = alpha,
    eta_hat        = eta,
    n              = n,
    m              = m,
    censoring_rate = (n - m) / n,
    W2             = W2,
    W2_crit        = W2_crit,
    W2_reject      = W2_reject,
    A2             = A2,
    A2_crit        = A2_crit,
    A2_reject      = A2_reject
  )

  cat("Критерии согласия:", result$test, "\n")
  cat("Распределение:", result$distribution, "\n")
  cat("Тип данных:", result$data_type, "\n")
  cat(result$hypothesis, "\n\n")

  cat("Оценки параметров:\n")
  cat("  eta_hat =", round(result$eta_hat, 4), "\n")
  cat("  alpha   =", round(result$alpha, 4), "\n\n")

  cat("Выборка:\n")
  cat("  n =", result$n, "\n")
  cat("  m =", result$m, "(наблюдаемых)\n")
  cat("  доля цензурирования =", round(result$censoring_rate, 4), "\n\n")

  cat("Результаты:\n")
  cat("  Крамер–фон Мизес:\n")
  cat("    W2      =", round(result$W2, 4), "\n")
  cat("    W2_crit =", round(result$W2_crit, 4), "\n")
  cat("    Вывод  ->",
      ifelse(result$W2_reject, "H0 отклоняется", "H0 не отклоняется"), "\n\n")

  cat("  Андерсон–Дарлинг:\n")
  cat("    A2      =", round(result$A2, 4), "\n")
  cat("    A2_crit =", round(result$A2_crit, 4), "\n")
  cat("    Вывод  ->",
      ifelse(result$A2_reject, "H0 отклоняется", "H0 не отклоняется"), "\n\n")

  return(invisible(result))
}

# ==============================================================================
# Пример использования (не выполняется при source)
# ==============================================================================

if (FALSE) {

  set.seed(123)
  n     <- 100
  x_obs <- sort(rexp(n, rate = 1))[1:80]   # выборка II типа: m = 80 из n = 100
  CENS.test.my(x_obs, n = n, alpha = 0.05)
}
